// Classic 5x7 column-major font, digits + the few symbols the pod needs.
// Rendered at integer scale; empty edge columns are trimmed by the renderer,
// which is what makes '1' naturally narrow (3 columns).

#ifndef FONT5X7_H
#define FONT5X7_H

#include <stdint.h>

typedef struct {
    char ch;
    uint8_t col[5]; // bit 0 = top row
} font_glyph_t;

static const font_glyph_t FONT5X7[] = {
    {'0', {0x3E, 0x51, 0x49, 0x45, 0x3E}},
    {'1', {0x00, 0x42, 0x7F, 0x40, 0x00}},
    {'2', {0x42, 0x61, 0x51, 0x49, 0x46}},
    {'3', {0x21, 0x41, 0x45, 0x4B, 0x31}},
    {'4', {0x18, 0x14, 0x12, 0x7F, 0x10}},
    {'5', {0x27, 0x45, 0x45, 0x45, 0x39}},
    {'6', {0x3C, 0x4A, 0x49, 0x49, 0x30}},
    {'7', {0x01, 0x71, 0x09, 0x05, 0x03}},
    {'8', {0x36, 0x49, 0x49, 0x49, 0x36}},
    {'9', {0x06, 0x49, 0x49, 0x29, 0x1E}},
    {'.', {0x00, 0x00, 0x60, 0x00, 0x00}},
    {'-', {0x08, 0x08, 0x08, 0x08, 0x08}},
    {'m', {0x7C, 0x04, 0x18, 0x04, 0x78}},
    {'C', {0x3E, 0x41, 0x41, 0x41, 0x22}},
    {'*', {0x00, 0x07, 0x05, 0x07, 0x00}}, // degree sign
    {'?', {0x02, 0x01, 0x51, 0x09, 0x06}},
    {'F', {0x7F, 0x09, 0x09, 0x09, 0x01}},
    {'M', {0x7F, 0x02, 0x0C, 0x02, 0x7F}},
    {'S', {0x46, 0x49, 0x49, 0x49, 0x31}},
    {' ', {0x00, 0x00, 0x00, 0x00, 0x00}},
};

static inline const uint8_t *font5x7_lookup(char c) {
    for (unsigned i = 0; i < sizeof(FONT5X7) / sizeof(FONT5X7[0]); i++) {
        if (FONT5X7[i].ch == c) return FONT5X7[i].col;
    }
    return FONT5X7[sizeof(FONT5X7) / sizeof(FONT5X7[0]) - 1].col; // space
}

#endif // FONT5X7_H
